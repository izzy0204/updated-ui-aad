def clean_text(text: str) -> str:
    return " ".join(str(text).replace("\n", " ").split())


def tokenize(text: str) -> List[str]:
    return [
        t.lower()
        for t in re.findall(r"[A-Za-z0-9]+", text)
        if len(t) > 1 and t.lower() not in _STOPWORDS
    ]


def score_passage(question: str, passage: str) -> float:
    q_set = set(tokenize(question))
    c_toks = tokenize(passage)
    if not q_set or not c_toks:
        return 0.0
    c_set = set(c_toks)
    overlap = len(q_set & c_set)
    return overlap / max(1.0, len(q_set) ** 0.5)


def extract_from_sections(sections: Dict[str, Dict[str, str]], chai_key: str) -> str:
    """Map parsed markdown sections to flat CHAI field names used in field_questions.json."""

    def _get_field(sec_substr: str, label: str) -> Optional[str]:
        for sec_name, fields in sections.items():
            if sec_substr in sec_name:
                val = fields.get(label)
                if val and str(val).strip():
                    return str(val).strip()
        return None

    if chai_key == "summary":
        v = _get_field("Metadata", "Summary")
        return v or ""
    if chai_key == "intended_use_and_workflow":
        v = _get_field("Uses", "Intended Use & Workflow") or _get_field("Directions", "Intended Use & Workflow")
        return v or ""
    if chai_key == "model_limitations":
        v = _get_field("Warnings", "Model Limitations")
        return v or ""
    if chai_key == "ai_system_facts":
        v = _get_field("Trust", "AI System Facts")
        return v or ""
    if chai_key == "usefulness_efficacy_result":
        for sec_name, fields in sections.items():
            if "Usefulness" in sec_name and "Efficacy" in sec_name:
                val = fields.get("Result")
                if val and str(val).strip():
                    return str(val).strip()
        return ""
    if chai_key == "safety_reliability_interpretation":
        for sec_name, fields in sections.items():
            if "Safety" in sec_name and "Reliability" in sec_name:
                val = fields.get("Interpretation")
                if val and str(val).strip():
                    return str(val).strip()
        return ""
    return ""


def load_card_flat(md_path: Path, repo_root: Path) -> Dict[str, Any]:
    """Load CHAI-like flat dict from optional outputs/<stem>.json else parsed markdown."""
    stem = md_path.stem
    json_sidecars = [
        repo_root / "outputs" / f"{stem}.json",
        md_path.with_suffix(".json"),
    ]
    for jp in json_sidecars:
        if jp.is_file():
            with open(jp, encoding="utf-8") as f:
                return json.load(f)

    raw = md_path.read_text(encoding="utf-8", errors="replace")
    md_norm = normalize_md_for_parsing(raw)
    body = body_before_references(md_norm, allow_sources_heading=False)
    sections = parse_model_card_md(body)
    out: Dict[str, Any] = {}
    keys = [
        "summary",
        "intended_use_and_workflow",
        "model_limitations",
        "ai_system_facts",
        "usefulness_efficacy_result",
        "safety_reliability_interpretation",
    ]
    for k in keys:
        out[k] = extract_from_sections(sections, k)
    return out


def chunk_markdown_body(body: str, *, min_chars: int = 120, max_chars: int = 1200) -> List[str]:
    """Split card body into retrieval chunks (paragraph-ish windows)."""
    body = re.sub(r"\n{3,}", "\n\n", body)
    paras = [p.strip() for p in body.split("\n\n") if p.strip()]
    chunks: List[str] = []
    buf = ""
    for p in paras:
        if len(buf) + len(p) + 1 <= max_chars:
            buf = f"{buf}\n\n{p}".strip() if buf else p
            continue
        if buf and len(buf) >= min_chars:
            chunks.append(buf)
        buf = p
    if buf and len(buf) >= min_chars:
        chunks.append(buf)
    elif buf and chunks:
        chunks[-1] = f"{chunks[-1]}\n\n{buf}"
    elif buf:
        chunks.append(buf)
    return chunks


def load_corpus_records(path: Path) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    if not path.is_file():
        return rows
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rows.append(json.loads(line))
    return rows


def write_corpus_jsonl(
    *,
    repo_root: Path,
    out_path: Path,
    card_specs: Sequence[Tuple[str, str]],
) -> None:
    """Build corpus from autogenerated card bodies (references stripped). One JSON object per line."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    records: List[Dict[str, Any]] = []
    for card_label, rel in card_specs:
        md_path = repo_root / rel
        if not md_path.is_file():
            continue
        raw = md_path.read_text(encoding="utf-8", errors="replace")
        md_norm = normalize_md_for_parsing(raw)
        body = body_before_references(md_norm, allow_sources_heading=False)
        chunks = chunk_markdown_body(body)
        slug = re.sub(r"[^a-z0-9]+", "_", card_label.lower()).strip("_")
        for i, ch in enumerate(chunks):
            records.append(
                {
                    "id": f"{slug}_{md_path.stem}_{i}",
                    "text": clean_text(ch),
                    "source": md_path.name,
                    "card_label": card_label,
                }
            )
    with open(out_path, "w", encoding="utf-8") as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")


def retrieve_contexts(
    question: str,
    corpus: Sequence[Dict[str, Any]],
    *,
    top_k: int,
    card_label: Optional[str],
    scope: str,
) -> List[str]:
    pool = list(corpus)
    if scope == "card" and card_label:
        pool = [r for r in corpus if r.get("card_label") == card_label]
    if not pool:
        pool = list(corpus)
    scored: List[Tuple[float, str]] = []
    for r in pool:
        text = r.get("text") or ""
        scored.append((score_passage(question, text), text))
    scored.sort(key=lambda x: x[0], reverse=True)
    out: List[str] = []
    seen: set[str] = set()
    for _, text in scored:
        if not text.strip():
            continue
        if text in seen:
            continue
        seen.add(text)
        out.append(text)
        if len(out) >= top_k:
            break
    return out


def serialize_contexts_cell(val: List[str]) -> str:
    return json.dumps(val, ensure_ascii=False)


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Build ragas_dataset.csv for UI autogenerated model cards.")
    p.add_argument(
        "--repo-root",
        type=Path,
        default=ROOT,
        help="Repository root (contains src/).",
    )
    p.add_argument(
        "--questions",
        type=Path,
        default=_DEFAULT_QUESTIONS,
        help="field_questions.json path.",
    )
    p.add_argument(
        "--corpus-out",
        type=Path,
        default=_DEFAULT_CORPUS,
        help="Where to write source_corpus.jsonl (chunked passages).",
    )
    p.add_argument(
        "--corpus-extra",
        type=Path,
        nargs="*",
        default=(),
        help="Optional extra .jsonl files merged into retrieval (same schema: id,text,source,...).",
    )
    p.add_argument(
        "--refresh-corpus",
        action="store_true",
        help="Rebuild source_corpus.jsonl from bundled A-card markdown before building rows.",
    )
    p.add_argument(
        "--dataset-out",
        type=Path,
        default=_DEFAULT_OUT,
        help="Output CSV path.",
    )
    p.add_argument("--top-k", type=int, default=5, help="Retrieved passages per question.")
    p.add_argument(
        "--retrieval-scope",
        choices=("card", "global"),
        default="card",
        help="Retrieve only from chunks of the same UI card (card) or from the full corpus (global).",
    )
    return p.parse_args()


def main() -> None:
    args = parse_args()
    repo_root = args.repo_root.resolve()

    if args.refresh_corpus or not args.corpus_out.is_file():
        write_corpus_jsonl(repo_root=repo_root, out_path=args.corpus_out, card_specs=UI_CARD_FILES)

    corpus = load_corpus_records(args.corpus_out)
    for extra in args.corpus_extra:
        corpus.extend(load_corpus_records(Path(extra).resolve()))

    if not corpus:
        raise SystemExit(
            f"No corpus rows loaded. Run with --refresh-corpus or populate {args.corpus_out}."
        )

    with open(args.questions, encoding="utf-8") as f:
        field_questions: Dict[str, str] = json.load(f)

    rows: List[Dict[str, Any]] = []
    for card_label, rel in UI_CARD_FILES:
        md_path = repo_root / rel
        if not md_path.is_file():
            print(f"Skip missing card: {md_path}", file=sys.stderr)
            continue
        card = load_card_flat(md_path, repo_root)

        for field, question in field_questions.items():
            answer = card.get(field, "")
            if not (isinstance(answer, str) and answer.strip()):
                continue
            cleaned = clean_text(answer)
            ctx_list = retrieve_contexts(
                question,
                corpus,
                top_k=args.top_k,
                card_label=card_label,
                scope=args.retrieval_scope,
            )
            rows.append(
                {
                    "card_label": card_label,
                    "card_file": md_path.name,
                    "field": field,
                    "question": question,
                    "answer": cleaned,
                    "contexts": serialize_contexts_cell(ctx_list),
                    "ground_truth": "",
                }
            )

    df = pd.DataFrame(rows)
    args.dataset_out.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(args.dataset_out, index=False)
    print(f"Saved {args.dataset_out} ({len(df)} rows)")


if __name__ == "__main__":
    main()
