ROOT = _HERE.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.core.dermauto_card_render import (  # noqa: E402
    body_before_references,
    normalize_md_for_parsing,
    parse_model_card_md,
)

# Matches sidebar labels in src/core/pages/03_DermAUTO_Card.py
# Only the autogenerated UI cards marked "A ·" are included for RAGAS runs by default.
UI_CARD_FILES: Tuple[Tuple[str, str], ...] = (
    ("A · DermaSensor", "src/core/pages/preloaded_cards/dermasensor-20260501-192348.md"),
    ("A · DermGPT", "src/core/pages/preloaded_cards/dermgpt-20260429-173126.md"),
    ("A · Tandem", "src/core/pages/preloaded_cards/tandem-20260501-043225.md"),
)

_DEFAULT_QUESTIONS = _HERE / "field_questions.json"
_DEFAULT_CORPUS = _HERE / "source_corpus.jsonl"
_DEFAULT_OUT = _HERE / "ragas_dataset.csv"

