"""
Build a RAGAS evaluation dataset for DermAUTO-CARD (UI "A" autogenerated markdown cards).

This does not score a static JSON card alone: each row simulates the RAG loop by pairing
field-specific questions with (1) the generated section text as the answer and (2) retrieved
passages from a dermatology corpus (chunked autogenerated card bodies + optional extra docs).

Methodological framing (what RAGAS answers here):
- Faithfulness: Are generated model-card statements grounded in retrieved sources?
- Answer relevancy: Does the generated section answer the field-specific question?
- Context precision: Are retrieved passages useful for the question/answer?
- Context recall: Did retrieval capture enough of the reference answer (needs ground_truth)?

Use SourceCheckup / FActScore-style checks separately for citation-to-claim support; use RAGAS
for retrieval + generation quality when contexts are present.

Python 3.11+.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

import pandas as pd

# Project imports (markdown parsing matches the DermAUTO-CARD UI)
